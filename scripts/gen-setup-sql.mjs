/**
 * Regenerates supabase/setup.sql from backend/src/db/ddl.ts.
 *
 * Run after any schema change:  node scripts/gen-setup-sql.mjs
 *
 * The DDL/seed section is byte-derived from the tested schema. The pg_cron and
 * RLS sections below it are Supabase-hosting-specific (no equivalent in local
 * dev, which never runs behind PostgREST) and are appended here so they survive
 * regeneration.
 */
import { writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { SCHEMA_SQL, SEED_PLANS_SQL } from "../backend/src/db/ddl.ts";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");

const header = `-- Routino database setup for Supabase.
-- Generated by scripts/gen-setup-sql.mjs from backend/src/db/ddl.ts (the same
-- DDL the test suites run) plus Supabase-hosting-specific sections below.
-- Idempotent (if not exists / on conflict) — safe to run more than once.
-- Apply: paste into the Supabase SQL Editor, or DATABASE_URL=... node scripts/apply-db-setup.mjs
`;

const cron = `
-- Hourly purge of expired OTP rows (the Node backend did this with setInterval;
-- edge functions have no resident process, so the database does it itself).
-- OTP rows double as the rate-limit ledger, so they must live 24h first.
create extension if not exists pg_cron;
select cron.schedule('routino-otp-purge', '0 * * * *',
  $$delete from otp_codes where created_at < now() - interval '24 hours'$$);
-- Aggregate auth counters are bounded by key/window and expire automatically.
select cron.schedule('routino-auth-rate-limit-purge', '30 * * * *',
  $$delete from auth_rate_limit_buckets where expires_at < now()$$);

-- Re-running setup must replace, not duplicate, the database-local compactor.
select cron.unschedule(jobid) from cron.job where jobname = 'routino-task-month-compaction';
select cron.schedule(
  'routino-task-month-compaction',
  '17 4 * * *',
  $$select * from routino_compact_task_months(now(), 500)$$
);

-- Tombstones, weekly. A deleted habit or log leaves a row behind on purpose: a
-- delete has to be able to TRAVEL to the user's other devices, and an absence
-- cannot. But it only has to travel once, so a user who tidies up their habits
-- every month should not keep carrying every tombstone forever.
--
-- The two halves must happen together, which is why this is one statement.
-- Raising \`users.gc_seq\` to the highest seq removed is what makes deleting a
-- tombstone safe: any device whose cursor still sits below that line is told to
-- wipe and resync from zero (\`reset: true\` in services/sync.ts) instead of
-- being allowed to miss the delete and silently RESURRECT the record. Delete
-- without the bump and a phone left in a drawer for four months comes back with
-- every habit its owner ever threw away.
--
-- 90 days is the promise: a device offline longer than that pays for a full
-- resync, which is correct but not free, so do not shorten this casually.
select cron.schedule('routino-tombstone-purge', '45 3 * * 0', $$
  with doomed as (
    delete from records
     where deleted = true
       -- 86400000::bigint, not a bare 90 * 86400000: that product is 7.7e9, which
       -- overflows int4 and fails the whole job with "integer out of range" —
       -- weekly, quietly, in a cron log nobody reads.
       and updated_at < (extract(epoch from now()) * 1000)::bigint - 90 * 86400000::bigint
    returning user_id, seq
  ), highest as (
    select user_id, max(seq) as top from doomed group by user_id
  )
  update users u set gc_seq = greatest(u.gc_seq, h.top)
    from highest h where u.id = h.user_id
$$);
`;

// Every table Supabase's PostgREST auto-exposes under /rest/v1/. Our backend
// NEVER goes through PostgREST — the edge function holds a direct Postgres
// connection as the `postgres` role, which OWNS these tables. Row Level
// Security does not apply to a table's owner (Postgres only enforces RLS on
// the owner if the table is explicitly FORCEd), so enabling RLS with zero
// policies is a pure lockdown: PostgREST's anon/authenticated roles get
// default-deny (no policy = no rows), while the edge function is unaffected.
// Without this, the Supabase anon key alone (meant to be public) would let
// anyone read/write users, payments, admins, otp_codes directly — bypassing
// every check in payment-flow.ts and the auth layer entirely.
const RLS_TABLES = [
  "users",
  "records",
  "otp_codes",
  "auth_rate_limit_buckets",
  "plans",
  "discounts",
  "redemptions",
  "payments",
  "grants",
  "entitlements",
  "feedback",
];

const rls = `
-- Lock every table out of Supabase's public PostgREST API (see comment in
-- scripts/gen-setup-sql.mjs). No policies are added on purpose: nothing but
-- the edge function's direct Postgres connection should ever touch these rows.
${RLS_TABLES.map((t) => `alter table ${t} enable row level security;`).join("\n")}
`;

writeFileSync(
  join(root, "supabase", "setup.sql"),
  header + SCHEMA_SQL + SEED_PLANS_SQL + cron + rls,
);
console.log(
  `[gen-setup-sql] supabase/setup.sql written (${RLS_TABLES.length} tables locked down with RLS)`,
);
